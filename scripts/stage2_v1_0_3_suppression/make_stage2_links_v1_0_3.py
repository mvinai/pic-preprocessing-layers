#!/usr/bin/env python3
"""Generate the Stage 2 v1.0.3 links file (stage2_v1_0_3_links.csv) from the COUNT-FIELD NAMES of a Stage 2 output.

Reads only `disclosure.count_fields` (JSON pointer names; never a value) of the given Stage 2 JSON and the v1.0.2
links file, and writes the v1.0.2 rows unchanged followed by the Stage 2 internal equalities that the v1.0.1
registry does not declare but a reader can make from the definitions in feature_sparsity_frequency_audit.py v1.0.1:

  L5a  layer_a/<split>/age_band/n_<band> = strata_denominators/age_band/<split>/<band>/n_encounters (same encounters,
       same age_band() array; one row per band that is a strata level)
  L5b  layer_a/dob_breakdown/by_split/<split>/n_invalid = layer_a/<split>/age_band/n_age_invalid (dob status != valid
       <=> age band age_invalid; the same equality the Stage 3 links v2 declare)
  L5c  layer_a/<split>/first_careunit/n_<unit> = strata_denominators/first_careunit/<split>/<unit>/n_encounters
  L6   layer_a/dob_breakdown/<cell> = sum over splits of layer_a/dob_breakdown/by_split/<split>/<cell> (status,
       n_invalid, n_age_days, negative bins); by_first_careunit/<unit>/<cell> = sum over splits of
       by_split_and_first_careunit/<split>/<unit>/<cell>
  L7   surgery/layer_a/<split>/n_encounters_recent = strata_denominators/surgical_status/<split>/recent_surgery/
       n_encounters (both: encounters with a linked surgery timed recent_layer_a)

Structural zeros (an age band that is no strata level, e.g. >= 18 years) are not links: they go to the team-internal
public file (value 0). A link is a modelling claim: if the released values contradict it, the suppression run stops.
Usage: make_stage2_links_v1_0_3.py <stage2.json> <v1.0.2 links.csv | -> <out.csv>"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

SPLITS = ("train", "validation", "test")
BANDS = ("neonate", "infant", "toddler", "preschool", "school", "adolescent", "ge18", "age_invalid")
DOB_CELLS = ("status/n_missing", "status/n_unparseable", "status/n_negative", "status/n_valid", "n_invalid",
             "n_age_days", "negative_bins/n_lt1d", "negative_bins/n_1to30d", "negative_bins/n_gt30d")
UNIT_CELLS = ("status/n_missing", "status/n_unparseable", "status/n_negative", "status/n_total", "n_invalid")
HEADER = ("# Stage 2 v1.0.3 links (suppression module v1.4). Rows 1-13: the v1.0.2 links, unchanged. Then the Stage 2\n"
          "# internal equalities L5 (age band / DOB / care unit vs strata denominators), L6 (DOB breakdown overall =\n"
          "# sum of splits) and L7 (recent surgery), generated by make_stage2_links_v1_0_3.py from count-field NAMES only.\n")


def enc(seg: str) -> str:
    return seg.replace("~", "~0").replace("/", "~1")


def levels(cf: set[str], var: str, split: str) -> list[str]:
    pre = f"/strata_denominators/{var}/{split}/"
    return sorted({c[len(pre):].rsplit("/", 1)[0] for c in cf if c.startswith(pre) and c.endswith("/n_encounters")})


def rows_for(cf: set[str]) -> list[tuple[str, str, str]]:
    out = []

    def add(total, parts, note):
        if total in cf and all(p in cf for p in parts):
            out.append((total, ";".join(parts), note))
    for s in SPLITS:
        for lv in levels(cf, "age_band", s):
            add(f"/layer_a/{s}/age_band/n_{lv}", [f"/strata_denominators/age_band/{s}/{lv}/n_encounters"],
                "L5a: same encounters (age_band() of the same split)")
        add(f"/layer_a/dob_breakdown/by_split/{s}/n_invalid", [f"/layer_a/{s}/age_band/n_age_invalid"],
            "L5b: DOB status not valid = age band age_invalid (same encounters)")
        for u in levels(cf, "first_careunit", s):
            add(f"/layer_a/{s}/first_careunit/n_{u}", [f"/strata_denominators/first_careunit/{s}/{u}/n_encounters"],
                "L5c: same encounters (first care unit of the same split)")
        add(f"/surgery/layer_a/{s}/n_encounters_recent",
            [f"/strata_denominators/surgical_status/{s}/recent_surgery/n_encounters"],
            "L7: encounters with a linked recent_layer_a surgery (same set)")
    d = "/layer_a/dob_breakdown"
    for c in DOB_CELLS:
        add(f"{d}/{c}", [f"{d}/by_split/{s}/{c}" for s in SPLITS], "L6: overall = sum of the three splits")
    units = sorted({c.split("/")[4] for c in cf if c.startswith(f"{d}/by_first_careunit/")})
    for u in units:
        for c in UNIT_CELLS:
            add(f"{d}/by_first_careunit/{u}/{c}", [f"{d}/by_split_and_first_careunit/{s}/{u}/{c}" for s in SPLITS],
                "L6: care unit overall = sum of the three splits")
    return out


def main(js: str, base: str, out: str) -> int:
    cf = set(json.loads(Path(js).read_text(encoding="utf-8"))["disclosure"]["count_fields"])
    base_rows = []
    if base != "-":
        with open(base, encoding="utf-8", newline="") as f:
            base_rows = [(r["total"], r["parts"], r["note"]) for r in csv.DictReader(l for l in f if not l.startswith("#"))]
    rows = base_rows + rows_for(cf)
    with open(out, "w", encoding="utf-8", newline="") as f:
        f.write(HEADER)
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["total", "parts", "note"])
        w.writerows(rows)
    print(f"{len(base_rows)} base rows + {len(rows) - len(base_rows)} new rows -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:4]))
